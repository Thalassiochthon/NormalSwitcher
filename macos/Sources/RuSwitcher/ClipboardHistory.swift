import AppKit
import ApplicationServices
import Carbon

struct ClipboardHistoryShortcut: Codable, Equatable {
    static let standard = Self(keyCode: UInt32(KC.letterV), modifiers: UInt32(controlKey | shiftKey), key: "V")

    let keyCode: UInt32
    let modifiers: UInt32
    let key: String

    var title: String {
        let symbols = [(controlKey, "⌃"), (optionKey, "⌥"), (shiftKey, "⇧"), (cmdKey, "⌘")]
        return symbols.compactMap { mask, symbol in modifiers & UInt32(mask) != 0 ? symbol : nil }
            .joined() + key
    }

    init?(keyCode: UInt16, flags: NSEvent.ModifierFlags, characters: String?) {
        guard flags.contains(.control) || flags.contains(.option) || flags.contains(.command),
              let key = characters,
              key.count == 1,
              let scalar = key.unicodeScalars.first,
              !CharacterSet.controlCharacters.contains(scalar),
              !(0xF700...0xF8FF).contains(scalar.value) else { return nil }
        let mapping: [(NSEvent.ModifierFlags, UInt32)] = [
            (.control, UInt32(controlKey)), (.option, UInt32(optionKey)),
            (.shift, UInt32(shiftKey)), (.command, UInt32(cmdKey)),
        ]
        self.init(keyCode: UInt32(keyCode),
                  modifiers: mapping.reduce(0) { $0 | (flags.contains($1.0) ? $1.1 : 0) },
                  key: scalar == " " ? "Space" : key.uppercased())
    }

    private init(keyCode: UInt32, modifiers: UInt32, key: String) {
        self.keyCode = keyCode
        self.modifiers = modifiers
        self.key = key
    }
}

@MainActor
final class ClipboardHistory {
    private static let limit = 30
    private static let maxTextBytes = 32 * 1024
    private static let shortcutID = EventHotKeyID(signature: 0x4E534348, id: 1) // NSCH
    private static let ignoredTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private let converter: TextConverter
    private let keyboardMonitor: KeyboardMonitor
    private var entries: [String] = []
    private var changeCount = 0
    private var timer: Timer?
    private var hotkey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var menuOpen = false
    private var selection: String?

    var shortcutAvailable: Bool { hotkey != nil }

    init(converter: TextConverter, keyboardMonitor: KeyboardMonitor) {
        self.converter = converter
        self.keyboardMonitor = keyboardMonitor
    }

    @discardableResult
    func configure() -> Bool {
        let settings = SettingsManager.shared
        if settings.clipboardHistoryEnabled {
            guard timer == nil else { return true }
            if settings.clipboardHistoryPersistent { load() }
            changeCount = pasteboard.changeCount
            let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.capture() }
            }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
            _ = registerShortcut(settings.clipboardHistoryShortcut)
            return true
        } else {
            stop()
            return clear()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let hotkey { UnregisterEventHotKey(hotkey) }
        if let handler { RemoveEventHandler(handler) }
        hotkey = nil
        handler = nil
    }

    @discardableResult
    func updatePersistence() -> Bool {
        if SettingsManager.shared.clipboardHistoryEnabled,
           SettingsManager.shared.clipboardHistoryPersistent {
            return save()
        }
        return removeSavedHistory()
    }

    private func capture() {
        let observedCount = pasteboard.changeCount
        guard observedCount != changeCount else { return }
        changeCount = observedCount
        // Secure Input applies to key monitoring, not an explicit copy to the pasteboard.
        guard !converter.hasTemporaryClipboardContents,
              let items = pasteboard.pasteboardItems, items.count == 1,
              let item = items.first,
              Self.ignoredTypes.allSatisfy({ !item.types.contains($0) }),
              !item.types.contains(.fileURL),
              let text = item.string(forType: .string),
              !text.isEmpty, text.utf8.count <= Self.maxTextBytes,
              pasteboard.changeCount == observedCount,
              entries.first != text else { return }
        entries.removeAll { $0 == text }
        entries.insert(text, at: 0)
        if entries.count > Self.limit { entries.removeLast() }
        if SettingsManager.shared.clipboardHistoryPersistent { _ = save() }
    }

    func show() {
        guard SettingsManager.shared.clipboardHistoryEnabled, !menuOpen, NSApp.modalWindow == nil else { return }
        capture()
        let target = NSWorkspace.shared.frontmostApplication
        let menu = NSMenu(title: L10n.clipboardHistoryTitle)
        if entries.isEmpty {
            let message: String
            if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
                message = L10n.clipboardHistoryAccessDenied
            } else {
                message = L10n.clipboardHistoryEmpty
            }
            menu.addItem(withTitle: message, action: nil, keyEquivalent: "")
        } else {
            for text in entries {
                let line = text.prefix(80).split(whereSeparator: \.isWhitespace).joined(separator: " ")
                let preview = line.isEmpty ? L10n.clipboardHistoryWhitespace : line
                let item = menu.addItem(withTitle: text.count > 80 ? preview + "…" : preview,
                                        action: #selector(selectEntry(_:)), keyEquivalent: "")
                item.target = self
                item.representedObject = text
            }
            menu.addItem(.separator())
            let clearItem = menu.addItem(withTitle: L10n.clipboardHistoryClear,
                                         action: #selector(clearFromMenu), keyEquivalent: "")
            clearItem.target = self
        }

        menuOpen = true
        menu.popUp(positioning: entries.isEmpty ? nil : menu.items.first,
                   at: NSEvent.mouseLocation, in: nil)
        menuOpen = false
        guard let text = selection else { return }
        selection = nil
        DispatchQueue.main.async { [weak self] in self?.paste(text, into: target) }
    }

    @objc private func selectEntry(_ sender: NSMenuItem) {
        selection = sender.representedObject as? String
    }

    @objc private func clearFromMenu() {
        if !clear() { showStorageError() }
    }

    @discardableResult
    private func clear() -> Bool {
        entries.removeAll()
        changeCount = pasteboard.changeCount
        return removeSavedHistory()
    }

    private func paste(_ text: String, into target: NSRunningApplication?) {
        guard SettingsManager.shared.clipboardHistoryEnabled,
              !converter.hasTemporaryClipboardContents else { return }
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else { return }
        // Leave the selected entry on the pasteboard even if focus or permissions changed.
        guard let target, NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier,
              AXIsProcessTrusted() else { return }
        keyboardMonitor.resetInputTracking()
        converter.pasteFromClipboard()
    }

    func changeShortcut(_ shortcut: ClipboardHistoryShortcut) -> Bool {
        let settings = SettingsManager.shared
        let previous = settings.clipboardHistoryShortcut
        if timer != nil {
            if shortcut == previous, shortcutAvailable { return true }
            if let hotkey { UnregisterEventHotKey(hotkey) }
            hotkey = nil
            guard registerShortcut(shortcut) else {
                _ = registerShortcut(previous)
                return false
            }
        }
        settings.clipboardHistoryShortcut = shortcut
        return true
    }

    private func registerShortcut(_ shortcut: ClipboardHistoryShortcut) -> Bool {
        guard handler != nil || installShortcutHandler() else { return false }
        return RegisterEventHotKey(shortcut.keyCode, shortcut.modifiers, Self.shortcutID,
                                   GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &hotkey) == noErr
    }

    private func installShortcutHandler() -> Bool {
        var event = EventTypeSpec(eventClass: OSType(kEventClassKeyboard),
                                  eventKind: UInt32(kEventHotKeyReleased))
        let target = GetApplicationEventTarget()
        return InstallEventHandler(target, { _, event, context in
            guard let event, let context else { return OSStatus(eventNotHandledErr) }
            var id = EventHotKeyID()
            let status = GetEventParameter(event, EventParamName(kEventParamDirectObject),
                                           EventParamType(typeEventHotKeyID), nil,
                                           MemoryLayout<EventHotKeyID>.size, nil, &id)
            return MainActor.assumeIsolated {
                guard status == noErr, id.signature == ClipboardHistory.shortcutID.signature,
                      id.id == ClipboardHistory.shortcutID.id else { return OSStatus(eventNotHandledErr) }
                let history = Unmanaged<ClipboardHistory>.fromOpaque(context).takeUnretainedValue()
                DispatchQueue.main.async { history.show() }
                return noErr
            }
        }, 1, &event, Unmanaged.passUnretained(self).toOpaque(), &handler) == noErr
    }

    private var storageURL: URL {
        URL.applicationSupportDirectory.appendingPathComponent("NormalSwitcher", isDirectory: true)
            .appendingPathComponent("ClipboardHistory", isDirectory: true)
            .appendingPathComponent("entries.json")
    }

    private func load() {
        guard let data = try? Data(contentsOf: storageURL),
              let saved = try? JSONDecoder().decode([String].self, from: data) else { return }
        entries = Array(saved.lazy.filter { !$0.isEmpty && $0.utf8.count <= Self.maxTextBytes }
            .prefix(Self.limit))
    }

    private func save() -> Bool {
        do {
            let url = storageURL
            let directory = url.deletingLastPathComponent()
            try FileManager.default.createDirectory(at: directory,
                                                    withIntermediateDirectories: true,
                                                    attributes: [.posixPermissions: 0o700])
            try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
            try JSONEncoder().encode(entries).write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return true
        } catch {
            rslog("Clipboard history could not be saved")
            return false
        }
    }

    private func removeSavedHistory() -> Bool {
        do {
            try FileManager.default.removeItem(at: storageURL)
            return true
        } catch let error as CocoaError where error.code == .fileNoSuchFile {
            return true
        } catch {
            rslog("Clipboard history could not be removed")
            return false
        }
    }

    func showStorageError() {
        let alert = NSAlert()
        alert.messageText = L10n.clipboardHistoryStorageError
        alert.runModal()
    }
}
