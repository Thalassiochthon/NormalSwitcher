import AppKit
import ApplicationServices
import Carbon

struct ClipboardHistoryShortcut: Codable, Equatable {
    static let standard = Self(keyCode: UInt32(KC.letterV), modifiers: UInt32(controlKey | shiftKey), key: "V")

    let keyCode: UInt32
    let modifiers: UInt32
    let key: String

    var title: String {
        let symbols = [(controlKey, "⌃"), (optionKey, "⌥"), (shiftKey, "⇧"), (cmdKey, "⌘")]
        return symbols.compactMap { mask, symbol in modifiers & UInt32(mask) != 0 ? symbol : nil }
            .joined() + key
    }

    private static let modifierMapping: [(NSEvent.ModifierFlags, UInt32)] = [
        (.control, UInt32(controlKey)), (.option, UInt32(optionKey)),
        (.shift, UInt32(shiftKey)), (.command, UInt32(cmdKey)),
    ]

    var menuKeyEquivalent: String { key == "Space" ? " " : key.lowercased() }

    var menuModifierFlags: NSEvent.ModifierFlags {
        Self.modifierMapping.reduce(into: []) { flags, entry in
            if modifiers & entry.1 != 0 { flags.insert(entry.0) }
        }
    }

    init?(keyCode: UInt16, flags: NSEvent.ModifierFlags, characters: String?) {
        guard flags.contains(.control) || flags.contains(.option) || flags.contains(.command),
              let key = characters,
              key.count == 1,
              let scalar = key.unicodeScalars.first,
              !CharacterSet.controlCharacters.contains(scalar),
              !(0xF700...0xF8FF).contains(scalar.value) else { return nil }
        self.init(keyCode: UInt32(keyCode),
                  modifiers: Self.modifierMapping.reduce(0) { $0 | (flags.contains($1.0) ? $1.1 : 0) },
                  key: scalar == " " ? "Space" : key.uppercased())
    }

    init(keyCode: UInt32, modifiers: UInt32, key: String) {
        self.keyCode = keyCode
        self.modifiers = modifiers
        self.key = key
    }
}

@MainActor
final class ClipboardHistory {
    static let limit = ClipboardHistoryStore.limit
    private static let maxTextBytes = ClipboardHistoryStore.maxTextBytes
    private static let shortcutID = EventHotKeyID(signature: 0x4E534348, id: 1) // NSCH
    private static let ignoredTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private let converter: TextConverter
    private let keyboardMonitor: KeyboardMonitor
    private let model = ClipboardHistoryModel()
    private var entries: [String] { model.entries }
    private var changeCount = 0
    private var timer: Timer?
    private var hotkey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var historyWindow: ClipboardHistoryWindow?
    private var pasteTarget: NSRunningApplication?

    var onAddTask: ((String) -> Void)?

    var shortcutAvailable: Bool { hotkey != nil }

    init(converter: TextConverter, keyboardMonitor: KeyboardMonitor) {
        self.converter = converter
        self.keyboardMonitor = keyboardMonitor
    }

    @discardableResult
    func configure() -> Bool {
        let settings = SettingsManager.shared
        if settings.clipboardHistoryEnabled {
            guard timer == nil else { return true }
            let restored = model.setPersistent(settings.clipboardHistoryPersistent)
            changeCount = pasteboard.changeCount
            let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.capture() }
            }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
            _ = registerShortcut(settings.clipboardHistoryShortcut)
            return restored
        } else {
            stop()
            return clear()
        }
    }

    func stop() {
        historyWindow?.close()
        historyWindow = nil
        timer?.invalidate()
        timer = nil
        if let hotkey { UnregisterEventHotKey(hotkey) }
        if let handler { RemoveEventHandler(handler) }
        hotkey = nil
        handler = nil
    }

    @discardableResult
    func updatePersistence() -> Bool {
        let result = model.setPersistent(SettingsManager.shared.clipboardHistoryEnabled &&
                                         SettingsManager.shared.clipboardHistoryPersistent)
        historyWindow?.update(entries: entries, storageFailed: model.storageFailed)
        return result
    }

    private func capture() {
        let observedCount = pasteboard.changeCount
        guard observedCount != changeCount else { return }
        changeCount = observedCount
        guard let text = currentText(maxBytes: Self.maxTextBytes), entries.first != text else { return }
        model.capture(text)
        historyWindow?.update(entries: entries, storageFailed: model.storageFailed)
    }

    func currentText(maxBytes: Int? = nil) -> String? {
        let version = pasteboard.changeCount
        guard !converter.hasTemporaryClipboardContents,
              let items = pasteboard.pasteboardItems, items.count == 1,
              let item = items.first,
              Self.ignoredTypes.allSatisfy({ !item.types.contains($0) }),
              !item.types.contains(.fileURL),
              let text = item.string(forType: .string),
              !text.isEmpty,
              maxBytes.map({ text.utf8.count <= $0 }) ?? true,
              pasteboard.changeCount == version else { return nil }
        return text
    }

    func show(for target: NSRunningApplication?) {
        guard SettingsManager.shared.clipboardHistoryEnabled, NSApp.modalWindow == nil else { return }
        if target?.processIdentifier != ProcessInfo.processInfo.processIdentifier { pasteTarget = target }
        capture()
        if let window = historyWindow?.window, window.isVisible {
            window.makeKeyAndOrderFront(nil)
            NSApp.activate(ignoringOtherApps: true)
            return
        }
        let emptyMessage: String
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            emptyMessage = L10n.clipboardHistoryAccessDenied
        } else {
            emptyMessage = L10n.clipboardHistoryEmpty
        }
        let browser = ClipboardHistoryWindow(entries: entries, storageFailed: model.storageFailed,
                                              emptyMessage: emptyMessage, onAddTask: onAddTask,
                                              onRetry: { [weak self] in
            guard let self else { return }
            _ = self.model.retry()
            self.historyWindow?.update(entries: self.entries, storageFailed: self.model.storageFailed)
        }, onClear: { [weak self] in
            guard let self else { return }
            if !self.clear() {
                self.historyWindow?.update(entries: self.entries, storageFailed: true)
            }
        }) { [weak self] text in
            guard let self else { return }
            let target = self.pasteTarget
            target?.activate(options: [])
            self.paste(text, into: target)
        }
        historyWindow = browser
        browser.showWindow(nil)
        NSApp.activate(ignoringOtherApps: true)
    }

    static func preview(_ text: String, limit: Int) -> String {
        let prefix = text.prefix(limit + 1)
        let line = prefix.prefix(limit).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        guard !line.isEmpty else { return L10n.clipboardHistoryWhitespace }
        return prefix.count > limit ? line + "…" : line
    }

    @discardableResult
    private func clear() -> Bool {
        guard model.clear() else { return false }
        changeCount = pasteboard.changeCount
        historyWindow?.close()
        return true
    }

    private func paste(_ text: String, into target: NSRunningApplication?) {
        guard SettingsManager.shared.clipboardHistoryEnabled,
              !converter.hasTemporaryClipboardContents else { return }
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else { return }
        // Leave the entry available for manual paste if the original target cannot take focus.
        guard let target, AXIsProcessTrusted() else {
            rslog("Clipboard history: entry copied; paste target or accessibility permission unavailable")
            return
        }
        deliverPaste(to: target, clipboardVersion: pasteboard.changeCount, attemptsLeft: 5)
    }

    private func deliverPaste(to target: NSRunningApplication, clipboardVersion: Int, attemptsLeft: Int) {
        guard SettingsManager.shared.clipboardHistoryEnabled, !target.isTerminated,
              pasteboard.changeCount == clipboardVersion, !converter.hasTemporaryClipboardContents else { return }

        let frontPID = NSWorkspace.shared.frontmostApplication?.processIdentifier
        if frontPID == target.processIdentifier, !AutoSwitchPolicy.secureInputActive {
            keyboardMonitor.resetInputTracking()
            converter.pasteFromClipboard(to: target.processIdentifier)
            return
        }

        // Closing our panel can keep focus briefly after the action. Wait only while no
        // other app has taken focus, and never redirect a paste to a different app.
        guard attemptsLeft > 0, frontPID == nil || frontPID == ProcessInfo.processInfo.processIdentifier else {
            rslog("Clipboard history: entry copied; automatic paste skipped (focus or secure input)")
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(50)) { [weak self] in
            self?.deliverPaste(to: target, clipboardVersion: clipboardVersion, attemptsLeft: attemptsLeft - 1)
        }
    }

    func changeShortcut(_ shortcut: ClipboardHistoryShortcut) -> Bool {
        let settings = SettingsManager.shared
        let previous = settings.clipboardHistoryShortcut
        if timer != nil {
            if shortcut == previous, shortcutAvailable { return true }
            if let hotkey { UnregisterEventHotKey(hotkey) }
            hotkey = nil
            guard registerShortcut(shortcut) else {
                _ = registerShortcut(previous)
                return false
            }
        }
        settings.clipboardHistoryShortcut = shortcut
        return true
    }

    private func registerShortcut(_ shortcut: ClipboardHistoryShortcut) -> Bool {
        guard handler != nil || installShortcutHandler() else { return false }
        return RegisterEventHotKey(shortcut.keyCode, shortcut.modifiers, Self.shortcutID,
                                   GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &hotkey) == noErr
    }

    private func installShortcutHandler() -> Bool {
        var event = EventTypeSpec(eventClass: OSType(kEventClassKeyboard),
                                  eventKind: UInt32(kEventHotKeyReleased))
        let target = GetApplicationEventTarget()
        return InstallEventHandler(target, { _, event, context in
            guard let event, let context else { return OSStatus(eventNotHandledErr) }
            var id = EventHotKeyID()
            let status = GetEventParameter(event, EventParamName(kEventParamDirectObject),
                                           EventParamType(typeEventHotKeyID), nil,
                                           MemoryLayout<EventHotKeyID>.size, nil, &id)
            return MainActor.assumeIsolated {
                guard status == noErr, id.signature == ClipboardHistory.shortcutID.signature,
                      id.id == ClipboardHistory.shortcutID.id else { return OSStatus(eventNotHandledErr) }
                let history = Unmanaged<ClipboardHistory>.fromOpaque(context).takeUnretainedValue()
                let target = NSWorkspace.shared.frontmostApplication
                DispatchQueue.main.async { history.show(for: target) }
                return noErr
            }
        }, 1, &event, Unmanaged.passUnretained(self).toOpaque(), &handler) == noErr
    }

    func showStorageError() {
        let alert = NSAlert()
        alert.messageText = L10n.clipboardHistoryStorageError
        alert.informativeText = taskText(
            "Check storage and Keychain access, then repeat the action in Settings or choose Retry in clipboard history. New entries are kept in memory until they can be saved.",
            "Проверьте доступ к хранилищу и Связке ключей. Повторите действие в настройках или нажмите «Повторить» в истории буфера. До успешного сохранения новые записи остаются в памяти.")
        alert.runModal()
    }
}
